function vocabularyFor(key) {
  if (key === "priority") return [
    { word: "priority", definition: "something that should be dealt with before other things", image_key: "factory" },
    { word: "time-sensitive", definition: "needing action within a limited amount of time", image_key: "project" },
    { word: "blocked", definition: "unable to continue because something is preventing progress", image_key: "factory" }
  ];
  if (key === "update") return [
    { word: "posted", definition: "kept informed about what is happening", image_key: "email" },
    { word: "status", definition: "the current condition or progress of something", image_key: "project" },
    { word: "follow up", definition: "to continue checking or communicating after an earlier action", image_key: "feedback" }
  ];
  return [
    { word: "align", definition: "to bring people, goals or plans into agreement", image_key: "meeting" },
    { word: "clarify", definition: "to make an idea or situation easier to understand", image_key: "feedback" },
    { word: "confirm", definition: "to state that something is correct, agreed or definite", image_key: "email" },
    { word: "move forward", definition: "to continue to the next stage of a plan or process", image_key: "project" }
  ];
}

function chooseChunk(text) {
  if (/priority|urgent|deadline/i.test(text)) return "This is a high priority.";
  if (/update|posted|status/i.test(text)) return "Keep me posted.";
  return "Let's align on this.";
}
function polishEnglish(text) {
  const cleaned = String(text || "").trim();
  if (!cleaned) return "";
  const out = cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
  return /[.!?]$/.test(out) ? out : `${out}.`;
}
function guessCategory(text) {
  const t = String(text || "").toLowerCase();
  if (t.includes("meeting") || t.includes("align") || t.includes("discuss")) return "Meeting";
  if (t.includes("production") || t.includes("test") || t.includes("issue") || t.includes("station")) return "Manufacturing";
  if (t.includes("email") || t.includes("send") || t.includes("report")) return "Email";
  if (t.includes("deadline") || t.includes("priority") || t.includes("urgent")) return "Deadline";
  if (t.includes("feedback")) return "Feedback";
  return "Workplace";
}
function imageKey(category) {
  return ({ Meeting:"meeting", Manufacturing:"factory", Email:"email", Deadline:"project", Feedback:"feedback" })[category] || "project";
}
