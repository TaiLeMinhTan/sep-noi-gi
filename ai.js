function demoAnalyze({ text, targetLanguage, user }) {
  const lang = LANGS[targetLanguage] || LANGS.en;
  const cleaned = String(text || "").trim().replace(/\s+/g, " ");
  const category = guessCategory(cleaned);
  const context = [user?.industry, user?.job_role].filter(Boolean).join(" · ");

  if (targetLanguage === "en") return englishChunkLesson(cleaned, category, context);

  return {
    provider: "demo",
    contract_version: "1.0",
    target_language: targetLanguage,
    target_language_name: lang.name,
    category,
    chunk: cleaned,
    pronunciation: "Pronunciation guide will be generated by the AI provider.",
    plain_description: `A concise ${lang.name}-only description will appear here. No native-language translation is required.`,
    usage: `Explain when, why and how this expression is used, entirely in ${lang.name}.`,
    image_key: imageKey(category),
    visual_concepts: ["situation", "people", "action", "result"],
    examples: [
      { text: cleaned, situation: category, image_key: imageKey(category) },
      { text: `A second natural example in ${lang.name}.`, situation: "Workplace", image_key: "project" },
      { text: `A third example adapted to ${context || "the learner's work"}.`, situation: "Your work", image_key: "feedback" }
    ],
    related_chunks: ["Related expression 1", "Related expression 2", "Related expression 3", "Related expression 4"],
    vocabulary: [
      { word: "Key word", definition: `Definition written only in ${lang.name}.`, image_key: "project" }
    ],
    suggested_replies: [`A natural reply in ${lang.name}.`, `A more concise reply in ${lang.name}.`],
    practice: {
      prompt: `Complete a sentence using this chunk in ${lang.name}.`,
      stem: cleaned,
      choices: ["before", "after", "while"],
      answer: "before"
    },
    thinking_prompt: `Describe the scene and intent directly in ${lang.name}; do not translate it into your native language.`
  };
}

